"""Which code revision the existing raw generation rows fall between.

    python generation/synthetic/infer_code_rev.py

Rows written from 2026-11-22 on carry `code_rev` (generate.py). The rows of
release synthetic-v1 were written before that field existed, and they are left
as they are. For them this script reads the row's `generated_utc` and the git
history and writes output/raw_generations_code_rev.csv, one line per group of
rows:

  config_hash, generator_version, plan_version   as on the rows
  code_rev                recorded on the row, empty for the old rows
  rev_before              last commit made before the row was generated
  rev_after               first commit made after it
  n, first_utc, last_utc  the rows in the group

This is an inference, not a record. A row was generated by the working tree of
its moment, which lies between `rev_before` and `rev_after` and need not equal
either. What does identify the generator's behaviour on every row is
`config_hash`: model, prompt, schema, sampling settings and judge.
"""
from __future__ import annotations

import csv
import json
import subprocess
from bisect import bisect_right
from collections import defaultdict
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "output" / "raw_generations.jsonl"
OUT = HERE / "output" / "raw_generations_code_rev.csv"


def commits() -> list[tuple[datetime, str]]:
    """(commit time, short revision) of every commit on HEAD, oldest first."""
    out = subprocess.run(["git", "log", "--format=%cI %h"], cwd=HERE, capture_output=True,
                         text=True, check=True).stdout.split("\n")
    pairs = [line.split(" ") for line in out if line.strip()]
    return sorted((datetime.fromisoformat(when), rev) for when, rev in pairs)


def main() -> None:
    history = commits()
    times = [when for when, _ in history]
    groups: dict[tuple, list[str]] = defaultdict(list)
    with RAW.open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            row = json.loads(line)
            stamp = row.get("generated_utc")
            i = bisect_right(times, datetime.fromisoformat(stamp))
            before = history[i - 1][1] if i else ""
            after = history[i][1] if i < len(history) else ""
            key = (row.get("config_hash") or "", row.get("generator_version") or "",
                   row.get("plan_version") or "", row.get("code_rev") or "", before, after)
            groups[key].append(stamp)

    rows = [[*key, len(stamps), min(stamps), max(stamps)] for key, stamps in groups.items()]
    rows.sort(key=lambda r: r[-2])
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["config_hash", "generator_version", "plan_version", "code_rev",
                    "rev_before", "rev_after", "n", "first_utc", "last_utc"])
        w.writerows(rows)
    for row in rows:
        print("  ".join(str(v) for v in row))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
